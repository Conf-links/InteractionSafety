"""Dataset statistics for the paper (no GPU): split-level prompt/pair counts, per-prompt agreement of the 7 response
models, and the source-dataset table. Splits are exactly the ones used everywhere else (common.load_splits).

Outputs: metrics/dataset_stats.csv, metrics/dataset_sources.csv, tables/tab_dataset_sources.tex,
         tables/tab_dataset_stats.tex
"""
import pandas as pd

import common as C

SOURCE_NAMES = {"xtram": "XTRAM", "arena": "Arena", "deepset": "deepset", "advbench": "AdvBench"}
N_MODELS = 7


def split_frames():
    tr, va, te = C.load_splits()
    return {"Train": tr, "Validation": va, "Test": te}


def stats(df):
    g = df.groupby("prompt_id").agg(n=("label", "size"), h=("label", "sum"), pl=("prompt_label", "first"))
    full = g[g.n == N_MODELS]
    return {
        "prompts": len(g), "benign_prompts": int((g.pl == 0).sum()), "malicious_prompts": int((g.pl == 1).sum()),
        "pairs": len(df), "harmful_pairs": int(df.label.sum()), "safe_pairs": int((df.label == 0).sum()),
        "harmful_pair_rate": df.label.mean(),
        "prompts_no_harmful_response": int((g.h == 0).sum()),
        "prompts_any_harmful_response": int((g.h > 0).sum()),
        "prompts_all_7_responses": len(full), "pairs_in_all_7_prompts": int(full.n.sum()),
        "all7_all_benign": int((full.h == 0).sum()), "all7_at_least_one_harmful": int((full.h > 0).sum()),
        "all7_all_harmful": int((full.h == N_MODELS).sum()),
        "all7_any_harmful_from_malicious_prompt": int(((full.h > 0) & (full.pl == 1)).sum()),
        "all7_any_harmful_from_benign_prompt": int(((full.h > 0) & (full.pl == 0)).sum()),
    }


def main():
    sp = split_frames()
    rows = {k: stats(v) for k, v in sp.items()}
    rows["Train+Val"] = stats(pd.concat([sp["Train"], sp["Validation"]]))
    rows["Total"] = stats(pd.concat(sp.values()))
    st = pd.DataFrame(rows)
    (C.NEW_RESULTS / "metrics").mkdir(exist_ok=True)
    st.to_csv(C.NEW_RESULTS / "metrics" / "dataset_stats.csv")

    # Source table counts every prompt of train.csv / test.csv. Train = train.csv minus the validation prompts, so it
    # also holds the prompts that have no labelled response in train_set.csv (absent from all pair-level experiments).
    src_tr, src_te = pd.read_csv(C.DATA_DIR / "train.csv"), pd.read_csv(C.DATA_DIR / "test.csv")
    val_ids = set(sp["Validation"].prompt_id)
    no_pairs = src_tr[~src_tr.prompt_id.isin(set(sp["Train"].prompt_id) | val_ids)]
    prompt_sets = {"Train": src_tr[~src_tr.prompt_id.isin(val_ids)], "Validation": src_tr[src_tr.prompt_id.isin(val_ids)],
                   "Test": src_te}
    order = ["Train", "Validation", "Test"]
    tab = []
    for name, p in prompt_sets.items():
        c = p.groupby(["source_dataset", "prompt_label"]).size().unstack(fill_value=0).reindex(columns=[0, 1], fill_value=0)
        c.columns = pd.MultiIndex.from_product([[name], ["Benign", "Malicious"]])
        tab.append(c)
    tab = pd.concat(tab, axis=1).fillna(0).astype(int)
    tab = tab.loc[[s for s in SOURCE_NAMES if s in tab.index]]
    tab.loc["Total"] = tab.sum()
    tab.to_csv(C.NEW_RESULTS / "metrics" / "dataset_sources.csv")

    T = C.NEW_RESULTS / "tables"
    L = ["% auto-generated by evaluation/code/dataset_stats.py  (needs booktabs)",
         "\\begin{table}[t]", "\\centering\\small",
         "\\caption{Prompts per source dataset and split. Benign/malicious is the prompt label of the source dataset. "
         "Validation is a 15\\% prompt-grouped hold-out of the training prompts (seed 42); every prompt is paired with "
         "the responses of 7 LLMs. "
         + (f"Train includes {len(no_pairs)} prompts with no labelled response "
            f"({', '.join(sorted(SOURCE_NAMES.get(s, s) for s in no_pairs.source_dataset.unique()))}, "
            f"{'malicious' if (no_pairs.prompt_label == 1).all() else 'mixed labels'}), which therefore appear in no "
            "prompt--response pair." if len(no_pairs) else "") + "}", "\\label{tab:dataset-sources}",
         "\\begin{tabular}{l" + "rr" * 3 + "r}", "\\toprule",
         "& \\multicolumn{2}{c}{Train} & \\multicolumn{2}{c}{Validation} & \\multicolumn{2}{c}{Test} & \\\\",
         "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}",
         "Source & Benign & Malicious & Benign & Malicious & Benign & Malicious & Total \\\\", "\\midrule"]
    for idx, r in tab.iterrows():
        if idx == "Total":
            L.append("\\midrule")
        vals = [f"{r[(s, c)]:,}".replace(",", "{,}") for s in order for c in ("Benign", "Malicious")]
        L.append(f"{SOURCE_NAMES.get(idx, idx)} & " + " & ".join(vals) + f" & {r.sum():,}".replace(",", "{,}") + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (T / "tab_dataset_sources.tex").write_text("\n".join(L) + "\n")

    f = lambda x: f"{int(x):,}".replace(",", "{,}")
    cols = ["Train", "Validation", "Test", "Total"]
    lines = [("Prompts", "prompts"), ("\\quad benign / malicious (source label)", None),
             ("Prompt--response pairs", "pairs"), ("\\quad harmful pairs ($y=1$)", "harmful_pairs"),
             ("\\quad harmful-pair rate", "harmful_pair_rate"),
             ("Prompts with all 7 responses labelled", "prompts_all_7_responses"),
             ("\\quad all 7 responses safe", "all7_all_benign"),
             ("\\quad $\\geq$1 harmful response", "all7_at_least_one_harmful"),
             ("\\quad all 7 responses harmful", "all7_all_harmful")]
    L = ["% auto-generated by evaluation/code/dataset_stats.py  (needs booktabs)",
         "\\begin{table}[t]", "\\centering\\small",
         "\\caption{Split statistics. A pair is labelled harmful ($y=1$) when the response itself is harmful. "
         "The last block counts prompts for which all 7 response models produced a labelled response.}",
         "\\label{tab:dataset-stats}", "\\begin{tabular}{lrrrr}", "\\toprule", " & " + " & ".join(cols) + " \\\\", "\\midrule"]
    for label, key in lines:
        if key is None:
            vals = [f"{f(st.loc['benign_prompts', c])} / {f(st.loc['malicious_prompts', c])}" for c in cols]
        elif key == "harmful_pair_rate":
            vals = [f"{100 * st.loc[key, c]:.1f}\\%" for c in cols]
        else:
            vals = [f(st.loc[key, c]) for c in cols]
        if key == "prompts_all_7_responses":
            L.append("\\midrule")
        L.append(f"{label} & " + " & ".join(vals) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (T / "tab_dataset_stats.tex").write_text("\n".join(L) + "\n")
    pd.set_option("display.width", 200)
    print(st.to_string()); print(tab.to_string())


if __name__ == "__main__":
    main()
