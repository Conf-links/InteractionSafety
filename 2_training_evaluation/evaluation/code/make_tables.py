"""LaTeX (booktabs) tables, written to evaluation/tables/ (and compact ones to compact/).

Needs \\usepackage{booktabs,graphicx} (and multirow for the strategy table). All numbers come from metrics/ and compact/.
  tab_dataset.tex          split sizes, harmful rate, generators, leakage checks
  tab_models.tex           architectures, parameter counts, adaptation method, hyper-parameters
  tab_compact_<crit>.tex   prompt-only zero-shot / prompt+response zero-shot / selected fine-tuned (+95% CIs)
  tab_strategies.tex       all strategies x classifiers at 100% response (appendix)
  tab_sweep_<crit>.tex     F1 and AUPRC at 0/20/50/100% response, zero-shot vs selected fine-tuned
  tab_subset.tex           harmful-prompt subset (response understanding only)
  tab_selection.tex        selected strategy under each criterion with its validation recall / F1
"""
import argparse
import json

import numpy as np
import pandas as pd

import common as C
from aggregate import CLASSIFIERS

M, T, COMPACT = C.NEW_RESULTS / "metrics", C.NEW_RESULTS / "tables", C.NEW_RESULTS / "compact"
NICE = {s: s.replace("_", " ") for s in C.STRATEGIES}


def f(x, d=3):
    return "--" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{d}f}"


def ci(r, m):
    return f"{f(r[m])} {{\\scriptsize[{f(r[m + '_lo'], 2)}, {f(r[m + '_hi'], 2)}]}}"


def write(path, body):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body)


def tab_dataset():
    tr, va, te = C.load_splits()
    rows = []
    for name, d in [("Train", tr), ("Validation", va), ("Test", te)]:
        rows.append(f"{name} & {d.prompt_id.nunique():,} & {len(d):,} & {int(d.label.sum()):,} & {100 * d.label.mean():.2f}\\% & "
                    f"{int((d.prompt_label == 1).sum()):,} & {int(((d.prompt_label == 1) & (d.label == 1)).sum()):,} \\\\")
    gens = sorted(te.model.unique())
    gen_rows = []
    for g in gens:
        a, b = pd.concat([tr, va]), te
        gen_rows.append(f"{g} & {int(a[a.model == g].label.sum())} / {int((a.model == g).sum()):,} & "
                        f"{int(b[b.model == g].label.sum())} / {int((b.model == g).sum()):,} \\\\")
    overlap = len(set(pd.concat([tr, va]).prompt_id) & set(te.prompt_id)), len(set(tr.prompt_id) & set(va.prompt_id))
    body = (
        "% auto-generated by evaluation/code/make_tables.py\n"
        "\\begin{table}[t]\n\\centering\\small\n"
        "\\caption{Dataset splits. Each prompt is answered by seven open LLMs; a pair is labelled harmful when the "
        "\\emph{response} provides harmful assistance. Validation is a prompt-grouped 15\\% split of the training file. "
        f"Prompt overlap: train--test {overlap[0]}, train--validation {overlap[1]}.}}\n"
        "\\label{tab:dataset}\n\\resizebox{\\columnwidth}{!}{%\n\\begin{tabular}{lrrrrrr}\n\\toprule\n"
        "Split & Prompts & Pairs & Harmful & Rate & Harm.\\ prompts & Harmful pairs w/ harm.\\ prompt \\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}}\n\n\\vspace{4pt}\n"
        "\\resizebox{0.8\\columnwidth}{!}{%\n\\begin{tabular}{lrr}\n\\toprule\nResponse generator & Train+val harmful / pairs & Test harmful / pairs \\\\\n\\midrule\n"
        + "\n".join(gen_rows) + "\n\\bottomrule\n\\end{tabular}}\n\\end{table}\n")
    write(T / "tab_dataset.tex", body)


